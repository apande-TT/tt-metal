// Attention softmax of float32 logits, one tile row (Wt tiles of 32 rows) at a time, bit-identical to the
// stock chain p = (s + mask - max(s + mask)).exp() / sum(...) it replaces. Each step makes the stock op's
// LLK calls with its configuration: every input buffer is unpacked to DEST as float32 (UnpackToDestFp32,
// as binary_ng / unary / the accurate fp32 reduce set it), fp32 DEST, math_approx_mode off.
//   x = s + bcast_row(mask)   binary_ng ROW_B LLK bcast: unary_bcast<ROW> + add_binary_tile<NearestEven>
//   mx = max_w(x)             accurate fp32 reduce W (SFPU): copy + binary_max_tile fold over the Wt tiles,
//                             then sfpu_reduce<MAX, REDUCE_ROW>, packed with the REDUCE_ROW edge mask
//   e = exp(x - bcast_col(mx)) binary_ng COL_B LLK bcast: unary_bcast<COL> + sub_binary_tile<NearestEven>,
//                             then unary exp_tile<false> (eltwise_sfpu.cpp with EXP param 0)
//   den = sum_w(e)            as mx with add_binary_tile (default rounding) and sfpu_reduce<SUM, REDUCE_ROW>
//   p = e / bcast_col(den)    binary_ng COL_B LLK bcast: unary_bcast<COL> + div_binary_tile
// Implicit tile padding (Sq or Sk not a multiple of 32): ttnn.max / ttnn.sum first fill the padding of their
// input in place (fill_implicit_tile_padding: FillPad with -inf for max, 0 for sum, on a view of the same
// buffer), so the subtract reads the -inf-filled x and the divide the 0-filled e. Here x's border tiles get
// -inf and e's border tiles 0 the way fill_pad_compute.cpp does it (mask tile -> DST 2, fill_tile_bitcast ->
// DST 1, where_tile<Float32>(2, 1, 0, 2): an exact select), before they are packed; the masks are the
// right / bottom / corner tiles fill_pad generates (generated by the reader with its generate_mask_tile).
// Every intermediate the stock chain writes to a float32 tensor stays float32 here (DEST or a float32 buffer),
// and the broadcasts are exact copies, so the same float32 operands reach the same SFPU ops in the same order.
// cb_x holds the row's Wt x tiles; the subtract / exp pass pops each x tile and pushes its e tile behind
// (the buffer is exactly Wt tiles, so e lands in x's place), and the divide pass pops the e tiles.

#include <cstdint>

#include "api/compute/bcast.h"
#include "api/compute/binary_max_min.h"
#include "api/compute/common.h"
#include "api/compute/compute_kernel_api.h"
#include "api/compute/compute_kernel_hw_startup.h"
#include "api/compute/eltwise_binary_sfpu.h"
#include "api/compute/eltwise_unary/exp.h"
#include "api/compute/eltwise_unary/fill.h"
#include "api/compute/eltwise_unary/where.h"
#include "api/compute/pack.h"
#include "api/compute/reduce.h"
#include "api/compute/reg_api.h"
#include "api/compute/tile_move_copy.h"
#include "api/dataflow/circular_buffer.h"

constexpr uint32_t cb_s = 0;     // logits, streamed by the reader
constexpr uint32_t cb_mask = 1;  // the Wt mask tiles of the current batch (row 0 valid)
constexpr uint32_t cb_x = 2;     // the row's Wt tiles: x, then e
constexpr uint32_t cb_mx = 3;    // row max (column 0 valid)
constexpr uint32_t cb_den = 4;   // row sum (column 0 valid)
constexpr uint32_t cb_pad = 5;   // padding masks (1.0 in the padding): right, bottom, corner (those present)
constexpr uint32_t cb_out = 16;  // probabilities, drained by the writer

// The accurate fp32 reduce W of compute_kernel_lib::reduce (REDUCE_ROW, SFPU path, WaitUpfront indexing):
// DST 0 = tile 0, then DST 1 = tile wt folded into DST 0, then the intra-tile row reduce; packed with the
// REDUCE_ROW edge mask like the stock output, the mask cleared again for the full-tile packs that follow.
template <ckernel::PoolType pool>
inline void reduce_row(uint32_t cb_in, uint32_t cb_red, uint32_t Wt) {
    CircularBuffer red(cb_red);
    red.reserve_back(1);
    tile_regs_acquire();
    copy_init(cb_in);
    if (Wt > 1) {
        if constexpr (pool == ckernel::PoolType::MAX) {
            binary_max_tile_init();
        } else {
            add_binary_tile_init();
        }
    }
    copy_tile(cb_in, 0, 0);
    for (uint32_t wt = 1; wt < Wt; ++wt) {
        copy_tile(cb_in, wt, 1);
        if constexpr (pool == ckernel::PoolType::MAX) {
            binary_max_tile(0, 1, 0);
        } else {
            add_binary_tile(0, 1, 0);
        }
    }
    sfpu_reduce_init<pool, DataFormat::Float32>();
    sfpu_reduce<pool, DataFormat::Float32, ckernel::ReduceDim::REDUCE_ROW>(0, 1, 1);
    tile_regs_commit();
    tile_regs_wait();
    PACK((llk_pack_reduce_mask_config<ckernel::ReduceDim::REDUCE_ROW, ckernel::PackMode::Default>(cb_red)));
    pack_tile(0, cb_red);
    PACK((llk_pack_reduce_mask_clear()));
    tile_regs_release();
    red.push_back(1);
}

// fill_pad_compute.cpp's process_masked_tile on the tile in DST 0: padding (mask tile pad_tile != 0) <- the
// fill bits, the rest kept; the result is in DST 2.
inline void fill_padding(uint32_t pad_tile, uint32_t fill_bits) {
    copy_init(cb_pad);
    copy_tile(cb_pad, pad_tile, 2);
    fill_tile_init();
    fill_tile_bitcast(1, fill_bits);
    where_tile_init();
    where_tile<DataFormat::Float32>(2, 1, 0, 2);
}

void kernel_main() {
    const uint32_t num_rows = get_arg_val<uint32_t>(0);
    const uint32_t start_row = get_arg_val<uint32_t>(1);

    constexpr uint32_t Wt = get_compile_time_arg_val(0);
    constexpr uint32_t Ht = get_compile_time_arg_val(1);
    constexpr uint32_t H = get_compile_time_arg_val(2);
    constexpr uint32_t mask_batches = get_compile_time_arg_val(3);
    constexpr bool has_mask = get_compile_time_arg_val(4) != 0;
    constexpr uint32_t w_mod = get_compile_time_arg_val(5);  // Sk % 32 (0: no right padding)
    constexpr uint32_t h_mod = get_compile_time_arg_val(6);  // Sq % 32 (0: no bottom padding)
    constexpr uint32_t num_pad = (w_mod != 0) + (h_mod != 0) + (w_mod != 0 && h_mod != 0);
    constexpr uint32_t pad_bottom = w_mod != 0 ? 1 : 0;  // index of the bottom mask in cb_pad (corner: + 1)
    constexpr uint32_t neg_inf_bits = 0xFF800000u;       // FillPad value of ttnn.max (-inf)
    constexpr uint32_t zero_bits = 0x00000000u;          // FillPad value of ttnn.sum (0.0)

    CircularBuffer in(cb_s);
    CircularBuffer x(cb_x);
    CircularBuffer mx(cb_mx);
    CircularBuffer den(cb_den);
    CircularBuffer out(cb_out);

    compute_kernel_hw_startup(cb_s, cb_out);
    if constexpr (num_pad > 0) {
        CircularBuffer pad(cb_pad);
        pad.wait_front(num_pad);
    }

    uint32_t mask_key = 0xFFFFFFFF;
    for (uint32_t r = start_row; r < start_row + num_rows; ++r) {
        const bool bottom = h_mod != 0 && r % Ht == Ht - 1;
        // the padding mask of tile wt of this row, or -1 for a tile without padding
        auto pad_tile = [&](uint32_t wt) -> int32_t {
            const bool right = w_mod != 0 && wt == Wt - 1;
            return right ? (bottom ? int32_t(pad_bottom + 1) : 0) : (bottom ? int32_t(pad_bottom) : -1);
        };

        // x = s + bcast_row(mask) (or x = s), padding <- -inf, Wt tiles into cb_x
        if constexpr (has_mask) {
            CircularBuffer mask(cb_mask);
            const uint32_t key = mask_batches == 1 ? 0 : r / Ht / H;
            if (key != mask_key) {  // the reader pushes the batch's mask tiles when the batch changes
                if (mask_key != 0xFFFFFFFF) {
                    mask.pop_front(Wt);
                }
                mask.wait_front(Wt);
                mask_key = key;
            }
        }
        for (uint32_t wt = 0; wt < Wt; ++wt) {
            in.wait_front(1);
            x.reserve_back(1);
            tile_regs_acquire();
            if constexpr (has_mask) {
                unary_bcast_init<ckernel::BroadcastType::ROW>(cb_mask);
                unary_bcast<ckernel::BroadcastType::ROW>(cb_mask, wt, 1);
            }
            copy_init(cb_s);
            copy_tile(cb_s, 0, 0);
            if constexpr (has_mask) {
                add_binary_tile_init();
                add_binary_tile<ckernel::DstRoundingMode::NearestEven>(0, 1, 0);
            }
            uint32_t res = 0;
            if (const int32_t pt = pad_tile(wt); pt >= 0) {
                fill_padding(pt, neg_inf_bits);
                res = 2;
            }
            tile_regs_commit();
            tile_regs_wait();
            pack_tile(res, cb_x);
            tile_regs_release();
            x.push_back(1);
            in.pop_front(1);
        }

        // mx = max over the row's Wt tiles
        x.wait_front(Wt);
        reduce_row<ckernel::PoolType::MAX>(cb_x, cb_mx, Wt);

        // e = exp(x - bcast_col(mx)), padding <- 0, each e tile in its x tile's place
        mx.wait_front(1);
        for (uint32_t wt = 0; wt < Wt; ++wt) {
            x.wait_front(1);
            tile_regs_acquire();
            unary_bcast_init<ckernel::BroadcastType::COL>(cb_mx);
            unary_bcast<ckernel::BroadcastType::COL>(cb_mx, 0, 1);
            copy_init(cb_x);
            copy_tile(cb_x, 0, 0);
            sub_binary_tile_init();
            sub_binary_tile<ckernel::DstRoundingMode::NearestEven>(0, 1, 0);
            exp_tile_init<false>();
            exp_tile<false>(0);
            uint32_t res = 0;
            if (const int32_t pt = pad_tile(wt); pt >= 0) {
                fill_padding(pt, zero_bits);
                res = 2;
            }
            tile_regs_commit();
            x.pop_front(1);
            x.reserve_back(1);
            tile_regs_wait();
            pack_tile(res, cb_x);
            tile_regs_release();
            x.push_back(1);
        }
        mx.pop_front(1);

        // den = sum over the row's Wt e tiles
        x.wait_front(Wt);
        reduce_row<ckernel::PoolType::SUM>(cb_x, cb_den, Wt);

        // p = e / bcast_col(den)
        den.wait_front(1);
        for (uint32_t wt = 0; wt < Wt; ++wt) {
            out.reserve_back(1);
            tile_regs_acquire();
            unary_bcast_init<ckernel::BroadcastType::COL>(cb_den);
            unary_bcast<ckernel::BroadcastType::COL>(cb_den, 0, 1);
            copy_init(cb_x);
            copy_tile(cb_x, 0, 0);
            div_binary_tile_init();
            div_binary_tile(0, 1, 0);
            tile_regs_commit();
            tile_regs_wait();
            pack_tile(0, cb_out);
            tile_regs_release();
            out.push_back(1);
            x.pop_front(1);
        }
        den.pop_front(1);
    }
    if constexpr (has_mask) {
        if (mask_key != 0xFFFFFFFF) {
            CircularBuffer mask(cb_mask);
            mask.pop_front(Wt);
        }
    }
    if constexpr (num_pad > 0) {
        CircularBuffer pad(cb_pad);
        pad.pop_front(num_pad);
    }
}
